args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==2)
e <- new.env(parent=baseenv())
load(args[1],envir=e)
stopifnot("replicate_mean" %in% ls(e))
d <- as.data.frame(e$replicate_mean)
cols <- c("replicate","treatment","predict_spec","NumDays","mean.dens.ml")
stopifnot(all(cols %in% names(d)))
write.csv(d[,cols],args[2],row.names=FALSE,na="NA")
cat("SHEN_SOURCE_OBJECT",nrow(d),ncol(d),paste(names(d),collapse="|"),"\n")
